def read_text(path: Path) -> str:
    raw = path.read_bytes()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        text = raw.decode("utf-16")
    else:
        text = raw.decode("utf-8", errors="strict")
    # Windows text-mode writers double the CR on CRLF input (the classic
    # newline=None gotcha); collapse any such damage and normalise to LF so
    # regenerated output is byte-stable regardless of the checkout style.
    while "\r\r\n" in text:
        text = text.replace("\r\r\n", "\r\n")
    return text.replace("\r\n", "\n")


def req(text: str, pattern: str, key: str, flags: int = 0) -> tuple:
    m = re.search(pattern, text, flags)
    if not m:
        raise SystemExit("parse failure: pattern for %r not found" % key)
    return m.groups()


def parse_measurement_log(text: str, label: str) -> dict:
    d: dict = {"label": label}
    c, N, dps, prec, algo, n = req(
        text,
        r"provenance\s*:\s*c=(\d+)\s+N=(\d+)\s+dps=(\d+)\s+prec=(\d+)\s+algo=(\S+)\s+n=(\d+)",
        label + " provenance",
    )
    d["prov"] = "c=%s N=%s dps=%s prec=%s algo=%s n=%s" % (c, N, dps, prec, algo, n)
    d["n"] = int(n)
    d["lambda_min"] = req(text, r"lambda_min = ([\d.eE+-]+)", label + " lambda_min")[0]
    d["lambda_max"] = req(text, r"lambda_max = ([\d.eE+-]+)", label + " lambda_max")[0]
    d["spread"] = req(text, r"spread\s+= ([\d.]+) orders", label + " spread")[0]
    rt = req(
        text,
        r"chart T \(ln lambda, PRIMARY\)\s+r_bar = ([\d.]+)\s+\(n_ratios = (\d+)",
        label + " S1 chart T",
    )
    d["rT"], d["rT_n"] = rt[0], int(rt[1])
    rl = req(
        text,
        r"chart L \(lambda, SECONDARY\)\s+r_bar = ([\d.]+)\s+\(n_ratios = (\d+)",
        label + " S1 chart L",
    )
    d["rL"], d["rL_n"] = rl[0], int(rl[1])
    gm, gs = req(
        text, r"^\s*gue\s+mean ([\d.]+)\s+sd ([\d.]+)", label + " GUE ref", re.M
    )
    d["gue_mean"], d["gue_sd"] = gm, gs
    d["s1_final"] = req(text, r"S1 FINAL:\s*([^\n]+)", label + " S1 FINAL")[0].strip()
    d["s2"] = {}
    for chart in ("T", "L"):
        for s in SIGMAS:
            pat_chi = (
                r"chart " + chart + r" \([^)]*\)\s+sigma_u " + re.escape(s)
                + r"\s*:\s*chi2 = ([\d.]+)"
            )
            m = re.search(pat_chi, text)
            if not m:
                raise SystemExit(
                    "parse failure: chi2 not found for %s chart %s sigma %s"
                    % (label, chart, s)
                )
            tail = text[m.end(): m.end() + 500]
            pg = re.search(r"p_GUE\s+= P\(chi2_GUE\s+>= chi2_obs\) = ([\d.]+)", tail)
            pp = re.search(r"p_Pois\s+= P\(chi2_Pois\s+<= chi2_obs\) = ([\d.]+)", tail)
            if not pg or not pp:
                raise SystemExit(
                    "parse failure: p-values not found for %s chart %s sigma %s"
                    % (label, chart, s)
                )
            d["s2"][(chart, s)] = {"chi2": m.group(1), "pGUE": pg.group(1), "pPois": pp.group(1)}
    d["s2_final"] = req(
        text, r"S2 FINAL[^\n]*:\s*([^\n]+)", label + " S2 FINAL"
    )[0].strip()
    m = re.search(r"RESOLUTION CEILING:\s*([^\n]+)", text)
    d["ceiling"] = m.group(1).strip() if m else None
    return d


def parse_capture(text: str, label: str) -> dict:
    out = {}
    out["lambda_min"] = req(text, r"lambda_min = ([\d.eE+-]+)", label + " lambda_min")[0]
    out["lambda_max"] = req(text, r"lambda_max = ([\d.eE+-]+)", label + " lambda_max")[0]
    out["spread"] = req(text, r"spread\s+= ([\d.]+) orders", label + " spread")[0]
    out["eig_s"] = req(text, r"STAGE 3 -- eig: ([\d.]+) s", label + " eig_s")[0]
    out["rad"] = req(
        text, r"radius worst \|rad\|/\|mid\|\s*:\s*1e(-[\d.]+)", label + " radius"
    )[0]
    if ">>> G-M0 PASS <<<" not in text:
        raise SystemExit("parse failure: capture log does not show G-M0 PASS")
    out["gate"] = "G-M0 PASS"
    return out


def sd_distance(r_bar: str, mean: str, sd: str) -> float:
    return (float(r_bar) - float(mean)) / float(sd)


def ladder_run(lad: dict, n_block: int) -> dict:
    for r in lad["runs"]:
        if r.get("N") == n_block:
            return r
    raise SystemExit("ladder JSON has no run with N=%d" % n_block)



# -*- coding: utf-8 -*-
"""Phase 3 -- resolution delta: dim 201 vs dim 401 Montgomery statistics.

WHAT THIS DOES
--------------
Reads the two CANONICAL measurement logs (never retyped by hand):

  msaf/mont_run.txt            dim 401 baseline. This is a UTF-16 copy of
                               gw_montgomery_100_200_run2.log -- the run
                               made AFTER defect 16 (false zero-radius
                               diagnostic) was fixed. Checked 2026-10-16:
                               r_bar and chi2 lines identical to run2.
  reports/mont_run_100_100.txt dim 201 run, 2026-10-16, same canonical
                               pipeline, 2000 samples, seed 20260927.

plus the two certified artifacts:

  reports/gw_route_s_ladder_c100.json  Route S inertia (CERTIFIED PD)
  reports/gw_capture_100_100.log       full-arb capture, G-M0 evaluation

and mutates section 4 of reports/THREE_TASKS_2026-10-15.md:

  1. the marker-delimited block
     <!-- BEGIN GW-DELTA ... --> ... <!-- END GW-DELTA -->
     is (re)generated in place; if the markers are absent the block is
     appended at the end of the file (idempotent either way);
  2. the old "Apakah deviasi mengecil atau membesar? TIDAK DIJAWAB"
     paragraph is replaced, once, by the answered version (fail-loud if
     neither the old text nor the new text is found -- nothing is ever
     silently skipped).

HONESTY NOTES
-------------
* Every number in the emitted section is parsed from its source file at
  generation time. A missing pattern aborts with SystemExit; it is never
  replaced by a guess.
* Raw chi2 is NOT comparable across N (pair counts scale as N^2); the
  comparable statistic is the matched-N Monte-Carlo p-value, which the
  section states.
* Default mode is a dry run; --write performs the file mutation.

usage:
    python msaf/gw_resolution_delta.py            # dry run, prints section
    python msaf/gw_resolution_delta.py --write    # mutate the report
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG401 = ROOT / "msaf" / "mont_run.txt"
LOG201 = ROOT / "reports" / "mont_run_100_100.txt"
LADDER = ROOT / "reports" / "gw_route_s_ladder_c100.json"
CAPTURE = ROOT / "reports" / "gw_capture_100_100.log"
REPORT = ROOT / "reports" / "THREE_TASKS_2026-10-15.md"

BEGIN = "<!-- BEGIN GW-DELTA (generated by msaf/gw_resolution_delta.py --write) -->"
END = "<!-- END GW-DELTA -->"
ANSWERED_HEAD = "#### Apakah deviasi mengecil atau membesar? **DIJAWAB (2026-10-16): TIDAK mengecil pada dua resolusi** -- tabel delta di \u00a74"

SIGMAS = ("0.3", "0.5", "1.0")


def read_text(path: Path) -> str:
    raw = path.read_bytes()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        text = raw.decode("utf-16")
    else:
        text = raw.decode("utf-8", errors="strict")
    # Windows text-mode writers double the CR on CRLF input (the classic
    # newline=None gotcha); collapse any such damage and normalise to LF so
    # regenerated output is byte-stable regardless of the checkout style.
    while "\r\r\n" in text:
        text = text.replace("\r\r\n", "\r\n")
    return text.replace("\r\n", "\n")


def req(text: str, pattern: str, key: str, flags: int = 0) -> tuple:
    m = re.search(pattern, text, flags)
    if not m:
        raise SystemExit("parse failure: pattern for %r not found" % key)
    return m.groups()


def parse_measurement_log(text: str, label: str) -> dict:
    d: dict = {"label": label}
    c, N, dps, prec, algo, n = req(
        text,
        r"provenance\s*:\s*c=(\d+)\s+N=(\d+)\s+dps=(\d+)\s+prec=(\d+)\s+algo=(\S+)\s+n=(\d+)",
        label + " provenance",
    )
    d["prov"] = "c=%s N=%s dps=%s prec=%s algo=%s n=%s" % (c, N, dps, prec, algo, n)
    d["n"] = int(n)
    d["lambda_min"] = req(text, r"lambda_min = ([\d.eE+-]+)", label + " lambda_min")[0]
    d["lambda_max"] = req(text, r"lambda_max = ([\d.eE+-]+)", label + " lambda_max")[0]
    d["spread"] = req(text, r"spread\s+= ([\d.]+) orders", label + " spread")[0]
    rt = req(
        text,
        r"chart T \(ln lambda, PRIMARY\)\s+r_bar = ([\d.]+)\s+\(n_ratios = (\d+)",
        label + " S1 chart T",
    )
    d["rT"], d["rT_n"] = rt[0], int(rt[1])
    rl = req(
        text,
        r"chart L \(lambda, SECONDARY\)\s+r_bar = ([\d.]+)\s+\(n_ratios = (\d+)",
        label + " S1 chart L",
    )
    d["rL"], d["rL_n"] = rl[0], int(rl[1])
    gm, gs = req(
        text, r"^\s*gue\s+mean ([\d.]+)\s+sd ([\d.]+)", label + " GUE ref", re.M
    )
    d["gue_mean"], d["gue_sd"] = gm, gs
    d["s1_final"] = req(text, r"S1 FINAL:\s*([^\n]+)", label + " S1 FINAL")[0].strip()
    d["s2"] = {}
    for chart in ("T", "L"):
        for s in SIGMAS:
            pat_chi = (
                r"chart " + chart + r" \([^)]*\)\s+sigma_u " + re.escape(s)
                + r"\s*:\s*chi2 = ([\d.]+)"
            )
            m = re.search(pat_chi, text)
            if not m:
                raise SystemExit(
                    "parse failure: chi2 not found for %s chart %s sigma %s"
                    % (label, chart, s)
                )
            tail = text[m.end(): m.end() + 500]
            pg = re.search(r"p_GUE\s+= P\(chi2_GUE\s+>= chi2_obs\) = ([\d.]+)", tail)
            pp = re.search(r"p_Pois\s+= P\(chi2_Pois\s+<= chi2_obs\) = ([\d.]+)", tail)
            if not pg or not pp:
                raise SystemExit(
                    "parse failure: p-values not found for %s chart %s sigma %s"
                    % (label, chart, s)
                )
            d["s2"][(chart, s)] = {"chi2": m.group(1), "pGUE": pg.group(1), "pPois": pp.group(1)}
    d["s2_final"] = req(
        text, r"S2 FINAL[^\n]*:\s*([^\n]+)", label + " S2 FINAL"
    )[0].strip()
    m = re.search(r"RESOLUTION CEILING:\s*([^\n]+)", text)
    d["ceiling"] = m.group(1).strip() if m else None
    return d


def parse_capture(text: str, label: str) -> dict:
    out = {}
    out["lambda_min"] = req(text, r"lambda_min = ([\d.eE+-]+)", label + " lambda_min")[0]
    out["lambda_max"] = req(text, r"lambda_max = ([\d.eE+-]+)", label + " lambda_max")[0]
    out["spread"] = req(text, r"spread\s+= ([\d.]+) orders", label + " spread")[0]
    out["eig_s"] = req(text, r"STAGE 3 -- eig: ([\d.]+) s", label + " eig_s")[0]
    out["rad"] = req(
        text, r"radius worst \|rad\|/\|mid\|\s*:\s*1e(-[\d.]+)", label + " radius"
    )[0]
    if ">>> G-M0 PASS <<<" not in text:
        raise SystemExit("parse failure: capture log does not show G-M0 PASS")
    out["gate"] = "G-M0 PASS"
    return out


def sd_distance(r_bar: str, mean: str, sd: str) -> float:
    return (float(r_bar) - float(mean)) / float(sd)


def build_section(a: dict, b: dict, lad: dict, cap: dict) -> str:
    run = lad["runs"][0]
    if not (run["n_pos"] == run["dim"] and run["n_neg"] == 0):
        raise SystemExit("ladder JSON does not show a fully positive inertia")
    dT401 = sd_distance(a["rT"], a["gue_mean"], a["gue_sd"])
    dT201 = sd_distance(b["rT"], b["gue_mean"], b["gue_sd"])
    pg401 = sorted({v["pGUE"] for v in a["s2"].values()})
    pg201 = sorted({v["pGUE"] for v in b["s2"].values()})

    def chi_row(d: dict, chart: str) -> str:
        return " / ".join(d["s2"][(chart, s)]["chi2"] for s in SIGMAS)

    def pois_row(d: dict, chart: str) -> str:
        return " / ".join(d["s2"][(chart, s)]["pPois"] for s in SIGMAS)

    lines = []
    add = lines.append
    add("## 4. Resolusi kedua (2026-10-16): dimensi 201 -- deviasi Montgomery mengecil atau membesar?")
    add("")
    add("*Seksi ini di-generate oleh `msaf/gw_resolution_delta.py` dari dua log kanonik "
        "(`msaf/mont_run.txt` = dim 401 pasca-perbaikan cacat 16; `reports/mont_run_100_100.txt` = dim 201) "
        "dengan instrumen yang sama (`gw_montgomery.py`, 2000 sampel N-matched, seed 20260927) dan aturan "
        "preregistrasi yang sama. Angka diekstrak mesin dari berkasnya, tidak diketik ulang.*")
    add("")
    add("### 4.1 Spektrum kedua, tersertifikasi penuh")
    add("")
    add("| Item | Nilai terukur |")
    add("|---|---|")
    add("| Ladder Route S 6000 bit (c=100, N=100) | %s -- n_pos = %d, n_neg = %d; build %s s; LDL^T %s s (`reports/gw_route_s_ladder_c100.json`) |"
        % (run["verdict"], run["n_pos"], run["n_neg"], run["build_s"], run["ldlt_s"]))
    add("| Capture penuh (arb), dim %d | %s 5/5; lambda_min = %s; lambda_max = %s; spread %s orders; radius terburuk `|rad|/|mid|` = 1e%s; eig %s s (`reports/gw_capture_100_100.log`) |"
        % (run["dim"], cap["gate"], cap["lambda_min"], cap["lambda_max"], cap["spread"], cap["rad"], cap["eig_s"]))
    add("| Chain capture | `build_arb_tau` -> `arb_mat.eig(vdhoeven_mourrain)` tanpa serialisasi desimal; deviasi rantai dari dim 401 dicatat di field `build_chain` |")
    add("")
    add("Biaya terukur titik baru: build %s s, LDL^T %s s (dim %d, 6000 bit). Dalam deret c=13 "
        "(0,84 s @ dim 81; 11,02 s @ 161; 83,01 s @ 321) titik ini jatuh di antara -- konsisten orde-kubik, "
        "tetapi konstanta biaya bergantung c; lintas-c bukan apel-samel, jadi ini rekor, bukan konfirmasi model."
        % (run["build_s"], run["ldlt_s"], run["dim"]))
    add("")
    add("### 4.2 Tabel delta (kedua kolom dari log kanonik)")
    add("")
    add("| Besaran | dim 401 (run2) | dim 201 (baru) |")
    add("|---|---|---|")
    add("| Provenance | %s | %s |" % (a["prov"], b["prov"]))
    add("| lambda_min (float, dari log) | %s | %s |" % (a["lambda_min"], b["lambda_min"]))
    add("| lambda_max | %s | %s |" % (a["lambda_max"], b["lambda_max"]))
    add("| spread | %s orders | %s orders |" % (a["spread"], b["spread"]))
    add("| S1 chart T `r_bar` (n_ratios) | %s (%d) | %s (%d) |" % (a["rT"], a["rT_n"], b["rT"], b["rT_n"]))
    add("| Referensi GUE matched-N (mean +- sd) | %s +- %s | %s +- %s |" % (a["gue_mean"], a["gue_sd"], b["gue_mean"], b["gue_sd"]))
    add("| Jarak `r_bar`-T dari rerata GUE (SD ensemble) | %+.2f | %+.2f |" % (dT401, dT201))
    add("| S1 chart L `r_bar` | %s | %s |" % (a["rL"], b["rL"]))
    add("| S1 FINAL | %s | %s |" % (a["s1_final"], b["s1_final"]))
    add("| S2 chi^2 chart T (sigma_u %s) | %s | %s |" % (" / ".join(SIGMAS), chi_row(a, "T"), chi_row(b, "T")))
    add("| S2 chi^2 chart L | %s | %s |" % (chi_row(a, "L"), chi_row(b, "L")))
    add("| S2 p_GUE (6 titik) | %s | %s |" % (" ; ".join(pg401), " ; ".join(pg201)))
    add("| S2 p_Pois chart T | %s | %s |" % (pois_row(a, "T"), pois_row(b, "T")))
    add("| S2 p_Pois chart L | %s | %s |" % (pois_row(a, "L"), pois_row(b, "L")))
    add("| S2 FINAL | %s | %s |" % (a["s2_final"], b["s2_final"]))
    add("")
    add("### 4.3 Jawaban")
    add("")
    add("**Tidak mengecil.** Pada instrumen S2 -- yang persis diadakan untuk menjawab pertanyaan ini -- "
        "p_GUE tetap di lantai uji di KEDUA resolusi: %s di keenam titik kisi dim 401, %s di keenam titik dim 201. "
        "Dengan 2000 surrogat, `0.0000` berarti chi^2_obs melebihi chi^2 SEMUA 2000 realisasi GUE berukuran sama; "
        "tidak ada titik kisi mana pun yang mendaki ke arah konsistensi."
        % (" ; ".join(pg401), " ; ".join(pg201)))
    add("")
    add("chi^2 mentah lintas-N bukan apel-samel (jumlah pasangan ~N^2/2 berbeda ~4x), jadi yang comparable adalah "
        "p-value matched-N -- dan p-value terkunci di lantai. Sebagai catatan tanpa pretensi: pada chart T chi^2 mentah "
        "dim 201 bahkan LEBIH BESAR dari dim 401 di dua dari tiga bandwidth (sigma_u 0,3 dan 0,5), padahal jumlah "
        "pasangan per bin turun sekitar setengah.")
    add("")
    add("S1 tetap buntu persis karena alasan yang sama seperti dim 401: chart T %s -> %s tetap ``CONSISTENT WITH RMT``, "
        "chart L %s -> %s tetap keluar dari ketiga referensi; selisih antar-chart bertahan (masing-masing dijelaskan "
        "rentang puluhan--ratusan order; lihat \"chart L non-uniform\" di aturan preregistrasi), dan S1 FINAL kedua "
        "resolusi tetap CHART-DEPENDENT -> INCONCLUSIVE. Perpindahan r_bar chart T di sekitar rerata GUE-nya: dari "
        "%+.2f SD (di bawah rerata) di dim 401 ke %+.2f SD (di atas rerata) di dim 201 -- tanda berbalik, magnitudo "
        "dalam satuan SD mengecil, tetapi dengan SATU matriks per resolusi itu tak terpisahkan dari fluktuasi sebesar "
        "ensemble-SD itu sendiri; itu bukan bukti tren."
        % (a["rT"], b["rT"], a["rL"], b["rL"], dT401, dT201))
    add("")
    add("Kesimpulan yang sah, dan hanya ini: pada dua resolusi yang tersedia, deviasi S2 terhadap kernel Montgomery "
        "**tidak mengecil** (rejeksi tetap di lantai uji), dan S1 tetap **INCONCLUSIVE** oleh chart-dependence. "
        "Dua titik tidak menetapkan arah asimtotik -- pertanyaan \"tren\" tetap butuh seri yang lebih panjang -- "
        "yang terjawab adalah versi ujinya: tidak ada pengecilan sampai konsisten pada N=201 dari N=401. "
        "Plafon resolusi kini terukur dua kali.")
    if a["ceiling"] and b["ceiling"]:
        add("")
        add("Plafon yang dicetak masing-masing run (dikutip apa adanya):")
        add("")
        add("- dim 401: %s" % a["ceiling"])
        add("- dim 201: %s" % b["ceiling"])
    add("")
    add("### 4.4 Cacat proses resolusi kedua, tercatat")
    add("")
    add("- **Skrip cepat S2 cacat, keluaran di-VOID.** Sebelum pipeline kanonik (`gw_montgomery.py`) ditemukan, "
        "sebuah reimplementasi cepat sempat dibuat dan dijalankan. Ia cacat ganda: parameter `sigma_u` tidak terpakai "
        "-- buktinya chi^2 identik di ketiga bandwidth (T: 2976.2575 tiga kali; L: 40194.1146 tiga kali), mustahil "
        "untuk sweep yang benar -- dan unfolding rank-based yang menghancurkan struktur pasangan. Seluruh keluarannya "
        "VOID dan telah dihapus; seluruh angka di seksi ini berasal dari pipeline kanonik.")
    add("- **Spektrum draf skema salah, dihapus.** Draft pertama dim 201 (mid float saja, tanpa radius, tanpa gate) "
        "dan pembangunnya telah dihapus; penggantinya adalah capture kanonik ber-G-M0 PASS di `reports/gw_spectrum_100_100.json`.")
    add("- **Sensor CI buta, diperbaiki di akar.** Sensor escape-token menyapu `lean/spec/` (9 axiom deklaratif yang "
        "memang di luar glob audit Python) sehingga CI merah di enam push berturut-turut sejak `29afa19`. Perbaikan "
        "`1d591a8`: kernel tetap wajib 0 hit; glob spec melarang `sorry/admit/unsafe` dan membekukan anggaran axiom "
        "di angka 9. CI hijau lagi (run 38832840886).")
    add("- **Provenance baseline.** `msaf/mont_run.txt` adalah salinan UTF-16 dari `gw_montgomery_100_200_run2.log` "
        "(baris r_bar dan chi^2 identik; beda 1 karakter akhir baris). Log `gw_montgomery_100_200.log` yang lebih lama "
        "tidak memuat statistik S1/S2 dan tidak dipakai.")
    add("")
    add("Batasan yang dibaca harfiah tetap sama: ini statistik dari dua matriks finit yang terbangun. Bukan teorema "
        "Montgomery, bukan bukti RH, bukan Weil-positivity, bukan penghitungan prima.")
    add("")
    return BEGIN + "\n\n" + "\n".join(lines) + "\n" + END


def main(argv: list) -> int:
    write = "--write" in argv
    a = parse_measurement_log(read_text(LOG401), "dim-401")
    b = parse_measurement_log(read_text(LOG201), "dim-201")
    lad = json.loads(read_text(LADDER))
    cap = parse_capture(read_text(CAPTURE), "capture-201")
    section = build_section(a, b, lad, cap)

    out = ["parsed OK:",
           "  dim-401: rT=%s rL=%s S1FINAL=%s" % (a["rT"], a["rL"], a["s1_final"]),
           "  dim-201: rT=%s rL=%s S1FINAL=%s" % (b["rT"], b["rL"], b["s1_final"]),
           "  p_GUE sets: 401=%s  201=%s" % (
               sorted({v["pGUE"] for v in a["s2"].values()}),
               sorted({v["pGUE"] for v in b["s2"].values()})),
           "  ladder: %s n+%d n-%d build %s ldlt %s" % (
               lad["runs"][0]["verdict"], lad["runs"][0]["n_pos"], lad["runs"][0]["n_neg"],
               lad["runs"][0]["build_s"], lad["runs"][0]["ldlt_s"]),
           "  capture: gate=%s lmin=%s eig=%s s" % (cap["gate"], cap["lambda_min"], cap["eig_s"]),
           ""]
    print("\n".join(out))

    text = read_text(REPORT)
    new_text = text
    if BEGIN in text and END in text:
        pre = text.split(BEGIN, 1)[0]
        post = text.split(END, 1)[1]
        new_text = pre.rstrip() + "\n\n" + section + "\n" + post.lstrip("\n")
        print("report: marker block replaced")
    else:
        new_text = text.rstrip() + "\n\n---\n\n" + section + "\n"
        print("report: marker block appended at end")

    if ANSWERED_HEAD in text:
        print("report: 'TIDAK DIJAWAB' already answered -- no further edit")
    else:
        pat = re.compile(
            r"#### Apakah deviasi mengecil atau membesar\? \*\*TIDAK DIJAWAB\*\*.*?(?=\nDan batasan yang harus dibaca harfiah)",
            re.S,
        )
        m = pat.search(new_text)
        if not m:
            raise SystemExit(
                "report: neither the old 'TIDAK DIJAWAB' block nor the answered "
                "heading was found -- refusing to write (nothing silently skipped)"
            )
        replacement = (
            ANSWERED_HEAD + "\n\n"
            "Spektrum tersertifikasi kedua sudah dibangun dan diukur (dim 201, c=100). Hasilnya seperti dim 401: "
            "**p_GUE terkunci di lantai uji (0,0000) di keenam titik kisi**, dan S1 tetap "
            "**CHART-DEPENDENT -> INCONCLUSIVE**. Arah asimtotik tetap tidak dapat disimpulkan dari dua titik; "
            "yang dapat disimpulkan: pada N=201 dari N=401, **tidak ada pengecilan menuju konsistensi**. "
            "Rincian, tabel delta, dan cacat proses: \u00a74.\n"
        )
        new_text = new_text[: m.start()] + replacement + new_text[m.end():]
        print("report: 'TIDAK DIJAWAB' block replaced by the answered version")

    if not write:
        print("")
        print("DRY RUN -- section preview below; rerun with --write to mutate the report")
        print("-" * 96)
        print(section)
        return 0

    if new_text == text:
        print("report unchanged (idempotent)")
        return 0
    REPORT.write_bytes(new_text.encode("utf-8"))
    print("written: %s" % REPORT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

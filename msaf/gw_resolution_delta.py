def main(argv: list) -> int:
    write = "--write" in argv
    a = parse_measurement_log(read_text(LOG401), "dim-401")
    b = parse_measurement_log(read_text(LOG201), "dim-201")
    lad = json.loads(read_text(LADDER))
    cap = parse_capture(read_text(CAPTURE), "capture-201")
    section = build_section(a, b, lad, cap)

    out = ["parsed OK:",
           "  dim-401: rT=%s rL=%s S1FINAL=%s" % (a["rT"], a["rL"], a["s1_final"]),
           "  dim-201: rT=%s rL=%s S1FINAL=%s" % (b["rT"], b["rL"], b["s1_final"]),
           "  p_GUE sets: 401=%s  201=%s" % (
               sorted({v["pGUE"] for v in a["s2"].values()}),
               sorted({v["pGUE"] for v in b["s2"].values()})),
           "  ladder: %s n+%d n-%d build %s ldlt %s" % (
               lad["runs"][0]["verdict"], lad["runs"][0]["n_pos"], lad["runs"][0]["n_neg"],
               lad["runs"][0]["build_s"], lad["runs"][0]["ldlt_s"]),
           "  capture: gate=%s lmin=%s eig=%s s" % (cap["gate"], cap["lambda_min"], cap["eig_s"]),
           ""]
    print("\n".join(out))

    text = read_text(REPORT)
    new_text = text
    if BEGIN in text and END in text:
        pre = text.split(BEGIN, 1)[0]
        post = text.split(END, 1)[1]
        new_text = pre.rstrip() + "\n\n" + section + "\n" + post.lstrip("\n")
        print("report: marker block replaced")
    else:
        new_text = text.rstrip() + "\n\n---\n\n" + section + "\n"
        print("report: marker block appended at end")

    if ANSWERED_HEAD in text:
        print("report: 'TIDAK DIJAWAB' already answered -- no further edit")
    else:
        pat = re.compile(
            r"#### Apakah deviasi mengecil atau membesar\? \*\*TIDAK DIJAWAB\*\*.*?(?=\nDan batasan yang harus dibaca harfiah)",
            re.S,
        )
        m = pat.search(new_text)
        if not m:
            raise SystemExit(
                "report: neither the old 'TIDAK DIJAWAB' block nor the answered "
                "heading was found -- refusing to write (nothing silently skipped)"
            )
        replacement = (
            ANSWERED_HEAD + "\n\n"
            "Spektrum tersertifikasi kedua sudah dibangun dan diukur (dim 201, c=100). Hasilnya seperti dim 401: "
            "**p_GUE terkunci di lantai uji (0,0000) di keenam titik kisi**, dan S1 tetap "
            "**CHART-DEPENDENT -> INCONCLUSIVE**. Arah asimtotik tetap tidak dapat disimpulkan dari dua titik; "
            "yang dapat disimpulkan: pada N=201 dari N=401, **tidak ada pengecilan menuju konsistensi**. "
            "Rincian, tabel delta, dan cacat proses: \u00a74.\n"
        )
        new_text = new_text[: m.start()] + replacement + new_text[m.end():]
        print("report: 'TIDAK DIJAWAB' block replaced by the answered version")

    # ---- section 5: the third resolution, only once its artifacts exist ----
    section3 = None
    have3 = (
        LOG301.exists()
        and CAPTURE301.exists()
        and any(r.get("N") == 150 for r in lad["runs"])
    )
    if have3:
        x301 = parse_measurement_log(read_text(LOG301), "dim-301")
        c3 = parse_capture(read_text(CAPTURE301), "capture-301")
        section3 = build_section3(b, x301, a, ladder_run(lad, 150), c3)
        if BEGIN3 in new_text and END3 in new_text:
            pre3 = new_text.split(BEGIN3, 1)[0]
            post3 = new_text.split(END3, 1)[1]
            new_text = pre3.rstrip() + "\n\n" + section3 + "\n" + post3.lstrip("\n")
            print("report: section 5 block replaced")
        else:
            new_text = new_text.rstrip() + "\n\n" + section3 + "\n"
            print("report: section 5 block appended")
    else:
        print("report: section 5 pending (dim-301 artifacts not present yet)")

    if not write:
        print("")
        print("DRY RUN -- section preview below; rerun with --write to mutate the report")
        print("-" * 96)
        print(section)
        if section3 is not None:
            print("-" * 96)
            print(section3)
        return 0

    if new_text == text:
        print("report unchanged (idempotent)")
        return 0
    REPORT.write_bytes(new_text.encode("utf-8"))
    print("written: %s" % REPORT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

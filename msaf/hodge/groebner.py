"""Multivariate polynomial core over F_p (graded lex) for Groebner bases.

Kept deliberately small and verifiable: monomials are tuples of
exponents, the order is graded lex, division is the textbook
leading-term algorithm. Used only by `quartic_surface` for the
smoothness certificate, and tested against ideals whose answers are
known by hand.
"""
from __future__ import annotations

__all__ = ["Poly", "groebner_contains_one"]


def _deg(e):
    return sum(e)


class Poly:
    """Sparse multivariate polynomial over F_p, dict exps -> coeff."""

    def __init__(self, p, terms=None):
        self.p = p
        self.terms: dict[tuple[int, ...], int] = {}
        if terms:
            for e, c in terms:
                if c % p:
                    self.terms[tuple(e)] = c % p

    def clone(self):
        q = Poly(self.p)
        q.terms = dict(self.terms)
        return q

    def is_zero(self):
        return not self.terms

    def key(self, e):
        return (_deg(e), e)

    def lead(self):
        if not self.terms:
            return None, 0
        best = max(self.terms, key=self.key)
        return best, self.terms[best]

    def add(self, other, sign=1):
        r = self.clone()
        for e, c in other.terms.items():
            r.terms[e] = (r.terms.get(e, 0) + sign * c) % self.p
            if r.terms[e] == 0:
                del r.terms[e]
        return r

    def scale(self, c):
        r = self.clone()
        c %= self.p
        if c == 0:
            return Poly(self.p)
        for e in r.terms:
            r.terms[e] = c * r.terms[e] % self.p
        return r

    def mul(self, other):
        r = Poly(self.p)
        for e1, c1 in self.terms.items():
            for e2, c2 in other.terms.items():
                e = tuple(e1[i] + e2[i] for i in range(len(e1)))
                r.terms[e] = (r.terms.get(e, 0) + c1 * c2) % self.p
        r.terms = {e: c for e, c in r.terms.items() if c % self.p}
        return r

    def shift(self, exps):
        r = Poly(self.p)
        for e, c in self.terms.items():
            r.terms[tuple(e[i] + exps[i] for i in range(len(e)))] = c
        return r

    def divides_lead(self, other):
        """True iff lead(other) divides lead(self) (this divides other)."""
        le, _ = other.lead()
        me, _ = self.lead()
        return all(me[i] <= le[i] for i in range(len(me)))

    def rem(self, g):
        """Multivariate remainder of self by g, textbook leading-term."""
        r = self.clone()
        gl, gc = g.lead()
        while not r.is_zero():
            rl, rc = r.lead()
            if not (all(gl[i] <= rl[i] for i in range(len(gl)))):
                break
            shift = tuple(rl[i] - gl[i] for i in range(len(rl)))
            fac = (rc * pow(gc, -1, self.p)) % self.p
            r = r.add(g.scale(fac).shift(shift), sign=-1)
        return r

    def is_constant_nonzero(self):
        return (
            len(self.terms) == 1
            and all(x == 0 for x in next(iter(self.terms)))
        )


def _s_poly(f, g, p):
    fe, fc = f.lead()
    ge, gc = g.lead()
    if fe == ge:
        return f.scale(pow(fc, -1, p)).add(
            g.scale(pow(gc, -1, p)), sign=-1
        )
    lcm = tuple(max(fe[i], ge[i]) for i in range(len(fe)))
    sf = tuple(lcm[i] - fe[i] for i in range(len(fe)))
    sg = tuple(lcm[i] - ge[i] for i in range(len(ge)))
    return f.scale(pow(fc, -1, p)).shift(sf).add(
        g.scale(pow(gc, -1, p)).shift(sg), sign=-1
    )


def _buchberger(polys, p, max_steps=5000):
    G = [g for g in polys if not g.is_zero()]
    seen = set()
    for g in G:
        seen.add(tuple(sorted(g.terms.items())))
    steps = 0
    i = 0
    while i < len(G):
        steps += 1
        if steps > max_steps:
            raise RuntimeError("Groebner basis exceeded step budget")
        for j in range(i + 1, len(G)):
            s = _s_poly(G[i], G[j], p)
            if s.is_zero():
                continue
            r = s
            for g in G:
                r = r.rem(g)
                if r.is_zero():
                    break
            if r.is_zero():
                continue
            r = r.scale(pow(r.lead()[1], -1, p))
            key = tuple(sorted(r.terms.items()))
            if key in seen:
                continue
            seen.add(key)
            G.append(r)
        i += 1
    return G


def groebner_contains_one(polys, p) -> bool:
    """True iff the ideal generated by ``polys`` is the unit ideal."""
    G = _buchberger(list(polys), p)
    return any(g.is_constant_nonzero() for g in G)